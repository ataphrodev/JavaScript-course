// Declaración de variables

// var, hoy en día NO se declara una variable con var, ya que tiene un scope global y puede generar problemas en el código.

var helloJavaScript = "Hello, JavaScript!"
console.log(helloJavaScript)

// let, permite declarar variables que pueden cambiar su valor, es decir, son variables mutables.

let helloJavaScript2 = "Hello, JavaScript 2!"
console.log(helloJavaScript2)
 
// const, no puede cambiar su valor, es decir, es una constante.

const helloJavaScript3 = "Hello, JavaScript 3!"
console.log(helloJavaScript3)